#!/usr/bin/env node
/**
 * Regenerate SIGNATURES.md from the signature database.
 *
 *   npm run signatures:md           # write the file
 *   node scripts/gen-signatures-md.mjs --check   # exit 1 if the file is stale (used by the tests)
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { describeSignatures } from '../src/core/signatures.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FILE = path.join(ROOT, 'SIGNATURES.md');

export function render() {
  const entries = describeSignatures();
  const cell = (s) => '`' + String(s).replace(/\|/g, '\\|') + '`';
  const rows = entries.map((e) => `| ${e.name} | ${e.examples.length > 0 ? e.examples.map(cell).join('<br>') : '(bot account)'} |`);

  return `# Signatures git-abv looks for

<!-- Generated by \`npm run signatures:md\` from src/core/signatures.js. Do not edit by hand. -->

git-abv counts a commit as AI-assisted only when the commit **says so itself**. This page lists
what "saying so" looks like for each of the ${entries.length} tools in the database.

A commit counts when any one of these is true:

1. **The author is an agent.** Its name or email matches a known agent identity, such as a GitHub App (\`devin-ai-integration[bot]\`).
2. **An agent is a co-author.** A \`Co-authored-by:\` trailer matches a known agent identity.
3. **A trailer says so.** Tool-specific trailers (\`Amp-Thread-ID:\`), or the free-form ones below.
4. **The message carries a tool's marker**, such as Claude Code's "Generated with" line.

## By tool

| Tool | Examples of what it matches |
| --- | --- |
${rows.join('\n')}

Matching is by pattern, not by these exact strings. For instance, any
\`Co-authored-by\` whose email is \`noreply@anthropic.com\` counts for Claude, whatever model name precedes it.

## Any tool: attribution trailers

The Linux kernel asks contributors to disclose AI help with an \`Assisted-by:\` trailer, and other
projects have adopted the same habit. git-abv reads these, and credits the **agent** rather than
the model it happened to run:

| Trailer | Counted as |
| --- | --- |
| \`Assisted-by: Claude:claude-sonnet-4-6\` | Claude |
| \`Assisted-by: Cursor:claude-opus-5\` | Cursor |
| \`Assisted-by: Codex\` | Codex |
| \`Assisted-by: Claude, Codex\` | Claude and Codex, half a commit each |
| \`Assisted-by: SomeAgent:some-model\` | Other AI |
| \`Assisted-by: LLM\` | Other AI |
| \`Generated-by: GitHub Copilot\` | Copilot |
| \`AI-assisted: yes\` | Other AI |
| \`Assisted-by: Jane Roe <jane@example.com>\` | not counted: that is a person |
| \`Assisted-by: smatch:2.0\`, \`coccinelle\`, \`sparse\`... | not counted: static analysers are not AI |

\`Generated-by:\`, \`AI-assisted-by:\` and \`AI-generated-by:\` are read the same way.

## What is deliberately not counted

- **People.** "Claude Dupont" is a colleague. A bare human-sounding name never counts without a machine's mailbox or a product name next to it.
- **Mentions.** "Copilot suggested this" in a commit body is prose, not a signature.
- **Reviews.** \`Reviewed-by:\` an AI is not authorship.
- **Plain automation.** Dependabot, Renovate, GitHub Actions and any other \`[bot]\` account that is not a known AI agent go into a separate *Bots* bucket, so a wall of dependency bumps never inflates the number.
- **Anything unsigned.** Autocomplete, pasted chat answers, and agents with attribution switched off leave no trace in git. That is why the result is a floor.

## Your own agents

Teams often run agents under a custom account. Tell git-abv about it:

\`\`\`bash
git abv --ai-identity '^acme-agent\\b'
\`\`\`

The pattern is a regular expression tested against \`Name <email>\` of authors and co-authors.

## Adding a signature

Found a tool git-abv misses? \`git abv --suspects\` lists bot-looking identities it does not recognise.
Then add a rule to [\`src/core/signatures.js\`](src/core/signatures.js), add a test, and run \`npm run signatures:md\`.
[CONTRIBUTING.md](CONTRIBUTING.md) has the details. One rule above all: **never match a human.**
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const expected = render();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(FILE) ? fs.readFileSync(FILE, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current !== expected) {
      console.error('SIGNATURES.md is out of date. Run: npm run signatures:md');
      process.exit(1);
    }
    console.log('SIGNATURES.md is up to date.');
  } else {
    fs.writeFileSync(FILE, expected);
    console.log(`Wrote SIGNATURES.md (${describeSignatures().length} tools).`);
  }
}
